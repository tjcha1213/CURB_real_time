"""Convert every public/data/*.json to a matching CSV in public/data/csv/.

Idempotent. Re-run after the fetch scripts (01-04) update the JSONs.

Conventions:
- Array-of-flat-object JSONs become straightforward row-per-record CSVs.
- Object JSONs are flattened with dotted keys (one row).
- Column order = first-seen key order across all rows (stable).
- Empty values render as the empty string, not "None".
"""
from __future__ import annotations

import csv
import json
import pathlib
from typing import Any, Iterable

DATA_DIR = pathlib.Path(__file__).resolve().parent.parent / "public" / "data"
CSV_DIR = DATA_DIR / "csv"
CSV_DIR.mkdir(parents=True, exist_ok=True)


def flatten(obj: Any, prefix: str = "") -> dict[str, Any]:
    """One-level dotted flatten — good enough for our shapes (no arrays of dicts inside)."""
    out: dict[str, Any] = {}
    if isinstance(obj, dict):
        for k, v in obj.items():
            key = f"{prefix}.{k}" if prefix else k
            if isinstance(v, dict):
                out.update(flatten(v, key))
            else:
                out[key] = v
    else:
        out[prefix or "value"] = obj
    return out


def collect_columns(rows: Iterable[dict]) -> list[str]:
    seen: list[str] = []
    seen_set: set[str] = set()
    for r in rows:
        for k in r.keys():
            if k not in seen_set:
                seen.append(k)
                seen_set.add(k)
    return seen


def write_csv(path: pathlib.Path, rows: list[dict]) -> None:
    if not rows:
        path.write_text("")
        print(f"  (empty) {path.name}")
        return
    cols = collect_columns(rows)
    with path.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        for r in rows:
            w.writerow({c: ("" if r.get(c) is None else r.get(c)) for c in cols})
    print(f"  wrote {path.name}  ({len(rows)} rows × {len(cols)} cols)")


def convert(json_path: pathlib.Path) -> None:
    raw = json_path.read_text().strip()
    if not raw:
        return
    payload = json.loads(raw)
    out = CSV_DIR / (json_path.stem + ".csv")

    if isinstance(payload, list):
        rows = [flatten(item) if isinstance(item, dict) else {"value": item} for item in payload]
        write_csv(out, rows)
    elif isinstance(payload, dict):
        write_csv(out, [flatten(payload)])
    else:
        write_csv(out, [{"value": payload}])


def write_index() -> None:
    """A small README so the csv/ folder is self-explanatory in the repo + on Pages."""
    readme = CSV_DIR / "README.md"
    rows: list[str] = [
        "# Processed data — CSV mirrors of public/data/*.json",
        "",
        "Auto-generated by `data-prep/05_export_csv.py`. Re-run after fetching.",
        "",
        "| File | Source script | Source page |",
        "|---|---|---|",
        "| `ma-bulky-tonnage.csv` | `03_fetch_massdep.py` | MassDEP 2024 Solid Waste Data Update |",
        "| `mattress-ban-before-after.csv` | `03_fetch_massdep.py` | EPR Commission Mattress Background Document, 2025-06-10 |",
        "| `mattress-policy-note.csv` | `03_fetch_massdep.py` | 310 CMR 19.017 / MassDEP mattress recycling guide |",
        "| `monthly-moveout-signal.csv` | `02_fetch_boston_311.py` | Analyze Boston — 311 Service Requests + Moving Truck Permits |",
        "| `boston-311-september.csv` | `02_fetch_boston_311.py` | Analyze Boston — 311 Service Requests |",
        "| `boston-cambridge-hotspots.csv` | `04_process_geo.py` | derived from Boston 311 + ACS housing units |",
        "| `cambridge-monthly.csv` | `01_fetch_cambridge.py` | Cambridge Open Data — Monthly Municipal Waste tonnage (`a249-j2dd`) |",
        "| `cambridge-311-dumping.csv` | `01_fetch_cambridge.py` | Cambridge Open Data — Commonwealth Connect Service Requests (`2z9k-mv9g`) |",
        "",
        "All weights are US short tons unless otherwise noted. Dates ISO-8601.",
    ]
    readme.write_text("\n".join(rows) + "\n")
    print(f"  wrote {readme.name}")


def main() -> None:
    print(f"[05_export_csv] -> {CSV_DIR.relative_to(DATA_DIR.parent.parent)}")
    for jp in sorted(DATA_DIR.glob("*.json")):
        convert(jp)
    write_index()


if __name__ == "__main__":
    main()
